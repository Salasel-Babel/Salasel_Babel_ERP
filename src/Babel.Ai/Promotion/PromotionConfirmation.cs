namespace Babel.Ai.Promotion;

/// <summary>
/// تأكيد بشري قبل الترقية: <b>من أكّد، وأي الحقول أكّد</b>.
/// <para>
/// وليس علماً منطقياً واحداً: الحقل المُصدَّق يُلمَح، والحقل المقروء أو المُستنتَج
/// <b>يُؤكَّد كلٌّ منه على حدة</b> — وهذا هو ما يمنع شاشةً تُدرِّب الإنسان على زرّ واحد.
/// </para>
/// </summary>
/// <param name="ConfirmedFields">مفاتيح الحقول المؤكَّدة.</param>
public sealed record PromotionConfirmation(IReadOnlySet<string> ConfirmedFields)
{
    /// <summary>
    /// <b>تصنيف المصروف كما كتبه الإنسان</b>، أو فارغ.
    /// <para>
    /// وهو الحقل الوحيد في هذا النوع الذي يحمل <b>قيمة</b> لا تأكيداً، ووجوده هنا لا في
    /// المسوّدة مقصود: التصنيف ليس على الفاتورة ولم يُقرأ منها، فليس له مصدرٌ في المسوّدة
    /// أصلاً. وهو يدخل من يد الإنسان لحظة التأكيد، فمصدره <c>Typed</c> بحكم موضعه لا
    /// بحكم وسمٍ يُكتب.
    /// </para>
    /// <para>وتركُه فارغاً حالةٌ مشروعة: الوحدة المالكة تُرحّل حينها بالمؤهّل العام.</para>
    /// </summary>
    public string ExpenseCategory { get; init; } = string.Empty;
}
