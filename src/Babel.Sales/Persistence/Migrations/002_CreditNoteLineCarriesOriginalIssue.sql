-- ولا فهرس عليه: القراءة تقع دائماً بمعرّف الإشعار المالك (OwnerType/OwnerId) وهو
-- مفهرس، وعمود إضافي في فهرس لا يُستعلَم به دينٌ لا فائدة له.
