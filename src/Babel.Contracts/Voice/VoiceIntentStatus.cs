namespace Babel.Contracts.Voice;

/// <summary>
/// حال النيّة في المنتج. <b>ووجود الحال الثانية هو ما يمنع التخمين</b>.
/// <para>
/// نيّةٌ يفهمها المستخدم ولا يستطيع السطح المنشور تنفيذها بمستندٍ واحد لا تُحذف —
/// فحذفُها يجعل المستخدم يقولها ويسمع «لم أفهم» وهي مفهومة تماماً. وتُنشر بحالٍ
/// <see cref="AwaitingOwnerDecision"/> فتقرأ الشرائح، ثم <b>ترفض التنفيذ برسالةٍ تسمّي
/// القرار الناقص بعينه</b>. وهذا هو الفرق بين نظامٍ يمتنع وبين نظامٍ يخترع.
/// </para>
/// </summary>
public enum VoiceIntentStatus
{
    /// <summary>منشورة: تُقرأ وتُؤكَّد وتُنفَّذ.</summary>
    Published = 1,

    /// <summary>
    /// تنتظر قراراً من مالك المنتج: تُقرأ شرائحُها وتُعرض، <b>ولا تُنفَّذ</b>،
    /// والرفض يسمّي القرار الناقص.
    /// </summary>
    AwaitingOwnerDecision = 2,
}
