-- هجرة المخزون 004 — للصنف دورة حياة، وليست حذفاً
-- ═══════════════════════════════════════════════════════════════════════════
--
-- **ما يتغيّر:** عمودٌ واحد — `inventory.item."IsActive"` — بافتراضٍ `true`.
--
-- **ولماذا `true` وليس فحصاً ولا تخميناً:** كل صنفٍ قائم اليوم **متداوَل**، لأن
-- النظام لم يكن يملك طريقاً لإيقافه أصلاً. فالافتراض هنا **إفادةٌ عن واقعة وقعت**
-- لا تقديرٌ: ما لم يُوقَف قطّ فهو عامل. ولو تُرك العمود بلا افتراض لصار كل صنفٍ
-- مضى «مُعطَّلاً» بأثر رجعي بمجرّد إضافة عمود — وهو تغييرُ حالةٍ لم يقرّره أحد.
--
-- **وما لا يُضاف: لا `deleted_at` ولا حذف.** رمزُ الصنف هوية تحملها قيود سنةٍ مضت،
-- وحذفُه يكسر كل تقرير مُرحَّل. والتعطيل **حالةٌ تُقرأ**، والمُعطَّل يبقى في القوائم.
--
-- **ولا كمّية تُعاد كتابتها ولا قيمة تُعاد حسابها.** والهجرة مكتوبة لتُعاد بلا أثر.

do $migration$
begin
    -- قاعدة لم يُنشأ فيها المخطّط بعد ليست حالة خطأ: EnsureCreated ينشئ الشكل
    -- الجديد كاملاً، ولا شيء هنا ليُرقّى.
    if to_regclass('inventory.item') is null then
        return;
    end if;

    alter table inventory.item
        add column if not exists "IsActive" boolean not null default true;
end
$migration$;
