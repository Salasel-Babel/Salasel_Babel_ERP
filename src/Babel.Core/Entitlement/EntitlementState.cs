namespace Babel.Core.Entitlement;

/// <summary>
/// حالات الاستحقاق الثلاث.
/// <para>
/// «إلغاء تثبيت وحدة» لا يمكن أن يوجد لوحدة رحّلت قيوداً غير قابلة للتعديل: القيود في الدفتر،
/// وفي ميزان المراجعة، وفي الإقرار المُقدَّم، وفي سلسلة التجزئة. إزالتها إتلاف للدفتر
/// (وثيقة المعمارية §17 م-7 · 06-risks-and-decisions.md ق-16).
/// </para>
/// <para>
/// <b>ولذلك <see cref="ReadOnly"/> يجب أن يوجد قبل أول عميل يدفع، لا بعد أول عميل يتوقف عن الدفع</b> —
/// إضافته لاحقاً تمسّ كل مسار كتابة وكل شاشة وكل تقرير في الوحدة.
/// </para>
/// الترتيب العددي هنا هو ترتيب القدرة، ويُعتمد عليه في تحقق الاتساق.
/// </summary>
public enum EntitlementState
{
    /// <summary>لم تُشترَ الوحدة قط. لا تظهر أصلاً، ولا تُقرأ ولا تُكتب.</summary>
    NotEntitled = 0,

    /// <summary>اشتُريت ثم انقضى الاشتراك: قراءة وتقارير كاملة، ولا مستند جديد ولا ترحيل جديد.</summary>
    ReadOnly = 1,

    /// <summary>مشتراة وفاعلة: قراءة وكتابة.</summary>
    Entitled = 2,
}
