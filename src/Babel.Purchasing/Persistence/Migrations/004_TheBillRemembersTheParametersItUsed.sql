-- هجرة المشتريات 004 — الفاتورة تتذكّر المعامِلات التي حُسبت بها
-- ═══════════════════════════════════════════════════════════════════════════
--
-- نسبةُ الضريبة على فاتورةٍ ملتقَطة قد تصل **من الخدمة** حين لا تُطبع على المستند.
-- والخدمة تُصدر إصداراتٍ مؤرَّخةَ السريان، ويُغيّرها صاحب المصلحة متى شاء. فلو حملت
-- الفاتورة النسبةَ وحدها لَما عرف قارئُها بعد سنتين **أيّ إصدارٍ** أنتجها، ولَقرأ
-- الإصدارَ الجاري فحسبه هو المستعمَل — وهو بالضبط «إعادةُ كتابة الماضي».
--
-- ‏**ولماذا نصٌّ لا مفتاحٌ أجنبي:** الإصدارات تعيش في قاعدة `babel_core` وهذه الفاتورة
-- في `babel_purchasing` (‏deploy/compose.yml يعطي كل وحدة قاعدةً منفصلة)، ومفتاحٌ
-- أجنبيّ عابرٌ للقواعد غير ممكن في PostgreSQL. فاللقطة تحمل **معرّف الإصدار والقيم
-- المستعمَلة معاً**، وتُقرأ من هذا الجدول وحده.
--
-- ‏**والقيمة الافتراضية فراغ، ومعناها معلَن:** «لم يُستعمل معامِل». والصفوف القائمة
-- كلّها كذلك فعلاً — لا مسار واحد في المنتج كان يقرأ معامِلاً قبل هذه الهجرة، والنسبة
-- كانت تصل مع الطلب دائماً. فالفراغ **إفادةٌ عن واقعة وقعت** لا تخمين.
--
-- ‏**وما لا تفعله هذه الهجرة:** لا تمسّ نسبةً واحدة، ولا تُعيد حساب ضريبة، ولا تُحرّك
-- قيداً. إضافةُ عمودِ وصفٍ لواقعةٍ مضت، لا إعادةُ كتابتها (‏ADR-0002).
--
-- والهجرة **معاملاتية** ومكتوبة لتُعاد بلا أثر.

do $migration$
begin
    -- قاعدة لم يُنشأ فيها المخطّط بعد ليست حالة خطأ: EnsureCreated ينشئ الشكل
    -- الجديد كاملاً، ولا شيء هنا ليُرقّى.
    if to_regclass('purchasing.supplier_bill') is null then
        return;
    end if;

    alter table purchasing.supplier_bill
        add column if not exists parameter_snapshot character varying(2000) not null default '';

    -- عمودٌ أُضيف في تشغيل سابق ثم عُدِّل بيدٍ خارجية: يُعاد إلى اصطلاح واحد.
    update purchasing.supplier_bill set parameter_snapshot = '' where parameter_snapshot is null;

    alter table purchasing.supplier_bill alter column parameter_snapshot set default '';
    alter table purchasing.supplier_bill alter column parameter_snapshot set not null;
end
$migration$;
