namespace Babel.Contracts.Lookup;

/// <summary>
/// <b>ما تُعلنه الوحدة المالكة من سجلّات أسماء — إعلانٌ لا اتصال.</b>
/// <para>
/// وهو نظير <c>IVoiceIntentCatalogue</c> مدخلاً بمدخل، وللسبب نفسه: شريحةٌ منطوقة تسمّي
/// سجلّاً لا تخدمه وحدةٌ واحدة <b>لا تُحلّ أبداً</b> — تُقرأ، وتُعلَّق، ولا يجيب عنها أحد،
/// فتظهر نيّةٌ «منشورة» لا تكتمل قطّ. وحارسٌ يقرأ هذه المجموعات ويطابقها بمفاتيح الشرائح
/// يجعل ذلك <b>يُحمِّر بوّابةً لا شاشةَ مستخدم</b>.
/// </para>
/// <para>
/// <b>ولماذا إعلانٌ منفصل عن <see cref="INameCandidateSource"/>:</b> المحوّل يحتاج نصَّ
/// اتصالٍ وقاعدةً حيّة، والحارس يحتاج <b>الأسماء وحدها</b>. وحارسٌ يشترط قاعدةً لا يُشغَّل
/// في البوّابة التي تُشغَّل أكثر، فيصير الحدُّ موصىً به لا مُنفَّذاً.
/// </para>
/// </summary>
public interface INameRegisterCatalogue
{
    /// <summary>مفاتيح السجلّات التي تملكها هذه الوحدة وتخدمها — مرتَّبة، وبلا تكرار.</summary>
    IReadOnlyList<string> RegisterKeys { get; }
}
