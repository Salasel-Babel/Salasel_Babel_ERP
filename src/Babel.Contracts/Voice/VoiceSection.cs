namespace Babel.Contracts.Voice;

/// <summary>
/// أقسام النظام الخمسة كما يراها المستخدم — <b>وهي وحدة تجميع النيّات المنطوقة</b>.
/// <para>
/// <b>ولماذا قسمٌ لا وحدة:</b> «المحاسبة» في فم المستخدم قسمٌ واحد، وهي في الشيفرة
/// وحدتان (المبيعات والمشتريات). ولو صار القسم هو الوحدة لَما استطاع مستخدمٌ أن يقول
/// «سجّل سند قبض» و«سجّل سند صرف» في مكان واحد. والعكس مرفوض أيضاً: قسمٌ يُشتقّ من
/// الوحدة يجعل تقسيم وحدةٍ غداً تقسيماً لقائمة يراها المستخدم على الشاشة.
/// </para>
/// </summary>
public enum VoiceSection
{
    /// <summary>المحاسبة — المبيعات والمشتريات والخزينة.</summary>
    Accounting = 1,

    /// <summary>المقاولات — العقود والمستخلصات والمقاولون من الباطن.</summary>
    Contracting = 2,

    /// <summary>الموارد البشرية — الموظفون والسلف والخصومات والرواتب.</summary>
    HumanResources = 3,

    /// <summary>المخزون — الأصناف والمستودعات والمواقع والوحدات.</summary>
    Inventory = 4,

    /// <summary>العقارات — العقارات والوحدات والمستأجرون والتحصيل.</summary>
    RealEstate = 5,
}
