using Babel.SharedKernel;

namespace Babel.Contracts.Voice;

/// <summary>
/// <b>خطّةٌ منطوقة — عدّةُ خطواتٍ من جملةٍ واحدة، وهي بيانات لا شيفرة.</b>
/// <para>
/// <b>الحاجة كما قيست على خادمٍ حيّ:</b> نطق المالكُ «سجّل سند قبض من شركة المسار
/// الأمثل <b>فإن لم تجدها أنشئ لها حساباً</b> ثم سند قبض بقيمة 20000…» — أمرٌ واحد
/// في فمه، وثلاثةُ أشياء في النظام: بحثٌ، وإنشاءٌ مشروط، ومسوّدة. وكان المسار المنطوق
/// يعرف <b>نيّةً واحدة لكل جملة</b>، فابتلع اسمُ العميل الشرطَ كلَّه.
/// </para>
/// <para>
/// <b>ولماذا تُعلَن في الوحدة المالكة لا في مشروع الذكاء:</b> خطّةٌ تركّب نيّاتِ
/// المبيعات هي شأنُ المبيعات، والوحدات الأفقية لا يعرف بعضها بعضاً (القاعدة 3).
/// والاتجاه مقلوبٌ هنا بالبناء نفسه الذي قلبته <see cref="IVoiceIntentCatalogue"/>:
/// النوعُ في العقد، والوحدةُ تُعلن، ووحدةُ الذكاء تجمع ما وجدته في الحاوية.
/// </para>
/// <para>
/// <b>وما لا تفعله الخطّة أبداً:</b> لا تُنفّذ، ولا تنادي باباً، ولا تُرحّل، ولا
/// تُجمِّع تأكيداً واحداً على عدّة مستندات. <b>كل خطوةٍ تمرّ من بوابة التأكيد وحدها
/// بملخّصها ورمزها</b>، لأن رمز التأكيد صورةٌ حتمية لأمرٍ <b>واحد</b>: رمزٌ يُحسب
/// مقدَّماً على قيمٍ لم توجد بعد إمّا أن يُسقطها — فيسقط معها المعنى الذي وُجد
/// <c>ConfirmationMismatch</c> ليحميه — أو يُعاد حسابه لاحقاً، وذلك ليس تأكيداً واحداً.
/// </para>
/// </summary>
/// <param name="Id">معرّف الخطّة — مقاطع لاتينية صغيرة تفصلها نقاط، فريدٌ عبر الوحدات.</param>
/// <param name="Section">القسم الذي يراه المستخدم.</param>
/// <param name="Module">الوحدة المالكة.</param>
/// <param name="NameAr">اسمها بالعربية كما يُقرأ في التوجيه — وهو السجلّ لا ترجمتُه.</param>
/// <param name="TriggerPhrases">
/// <b>ما يريده الإنسان</b> — بدائل، يكفي أن تظهر إحداها: «سند قبض».
/// </param>
/// <param name="ConditionPhrases">
/// <b>الشرطُ الذي يجعل الجملة خطّةً لا أمراً واحداً</b> — بدائل كذلك: «فإن لم تجدها»،
/// «وإلّا»، «إن لم يكن موجوداً».
/// <para>
/// <b>ولماذا حقلان لا حقلُ عباراتٍ واحد — وهو درسٌ قِيس لا رأيٌ اختير:</b> جُرِّبت
/// المطابقةُ أوّلاً بعباراتٍ كاملة كما تُطابَق النيّة (احتواءُ نصٍّ فرعيّ)، فسقطت على
/// جملة المالك نفسها: «سجّل سند قبض <b>من شركة المسار الأمثل</b> فإن لم تجدها…» —
/// فالطلبُ والشرطُ <b>ليسا متجاورين</b>، بينهما اسمُ العميل، وكلُّ عبارةٍ كاملة تُكتب
/// هنا كانت ستفترض جواراً لا يقع في كلام الناس.
/// </para>
/// <para>
/// <b>والصواب هو ما يقوله اللسان:</b> الخطّة تُعرَف بـ<b>اجتماع</b> طلبٍ وشرط، لا
/// بعبارةٍ واحدة. ومن ثمّ: تُطابق الخطّةُ إذا ظهر طلبٌ <b>وظهر</b> شرط — وهو دليلٌ
/// <b>أقوى</b> من دليل النيّة المفردة، ولذلك تفوز الخطّةُ حين تُطابق. وجملةٌ بلا شرطٍ
/// تبقى نيّةً واحدة كما كانت، فلا تنكسر جملةٌ تعمل اليوم.
/// </para>
/// </param>
/// <param name="Steps">خطواتها بترتيبها.</param>
public sealed record VoicePlan(
    string Id,
    VoiceSection Section,
    BabelModule Module,
    string NameAr,
    IReadOnlyList<string> TriggerPhrases,
    IReadOnlyList<string> ConditionPhrases,
    IReadOnlyList<VoicePlanStep> Steps);
