namespace Babel.Ai.Voice;

/// <summary>
/// <b>مقطعٌ من الكلام كما سُمع — ولا حكم فيه.</b>
/// <para>
/// هذا النوع هو ما بقي من «قراءة الاسم» بعد أن رُفع القرار من القارئ: لم يعد يقول
/// «هذا هو العميل»، بل «هذا ما قيل في موضع العميل». والفرق ليس لفظياً — القارئ لا يملك
/// ما يميّز بين مقطعين كلاهما اسمُ منشأةٍ صحيح الشكل في الجملة نفسها، <b>والسجلّ يملكه</b>.
/// </para>
/// <para>
/// و<see cref="Start"/> و<see cref="End"/> بالكلمات لا بالمحارف: المقطع يُعاد بناؤه من
/// الكلمات المُجرَّدة تجريداً أميناً، وهو ما يُعرض على الإنسان وما يُرسَل إلى السجلّ.
/// </para>
/// </summary>
/// <param name="Text">المقطع نصّاً، بالكلمات كما نُطقت.</param>
/// <param name="Start">موضع أول كلمة فيه.</param>
/// <param name="End">موضع ما بعد آخر كلمة فيه.</param>
public sealed record SpokenSpan(string Text, int Start, int End);
