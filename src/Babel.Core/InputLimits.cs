namespace Babel.Core;

/// <summary>
/// <b>حدودُ ما يكتبه إنسان — مصدرٌ واحد، ويُنشر في العقد.</b>
/// <para>
/// كانت الحدودُ نفسها مكتوبةً في ثلاثة أنواع: <c>CompanySetupLimits</c> و<c>ProfileLimits</c>
/// و<c>AccessLimits</c> — طولُ الاسم مرّتين بالرقم نفسه، وطولُ السبب وحدُّه الأدنى ثلاثَ
/// مرّات — وكان عمودُ <c>suspension_reason</c> في القاعدة أضيقَ ممّا يقبله المجال (400 مقابل
/// 512)، فسببٌ مقبولٌ في النوع يسقط في القاعدة. ونسختان من رقمٍ واحد تفترقان يوماً، وهذا
/// ما وقع.
/// </para>
/// <para>
/// <b>والقيمُ هنا سياسةُ تحريرٍ مُعلَنة لا ثابتةُ نوع:</b> «ثمانيةُ محارف تكفي سبباً» حكمٌ
/// تحريريّ، و«مئتا محرفٍ تكفي اسماً» كذلك. وهي في مصدرٍ واحد كي تتغيّر مرّةً واحدة، وتُنشر في
/// العقد (<c>minLength</c>/<c>maxLength</c>) كي تقرأها الواجهةُ منه لا تكتبها ثانيةً بيدها
/// (ADR-0091). وما يحكمه المخطّط — أطوالُ الأعمدة — يُشتقّ منها لا يُكتب بجوارها.
/// </para>
/// </summary>
public static class InputLimits
{
    /// <summary>أقصى طولِ اسمٍ يكتبه إنسان — منشأةً أو مركزَ تكلفةٍ أو عضواً.</summary>
    public const int MaximumNameLength = 200;

    /// <summary>أدنى طولِ سببٍ مكتوب — «لا سبب» ليس سبباً، وحرفان ليسا سبباً.</summary>
    public const int MinimumReasonLength = 8;

    /// <summary>أقصى طولِ سببٍ مكتوب — وهو طولُ عمود السبب في القاعدة بعينه.</summary>
    public const int MaximumReasonLength = 512;
}
