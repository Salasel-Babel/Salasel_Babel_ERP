/// <summary>
/// <b>الوحدةُ الصغرى لكلّ عملة كما تنصّ عليها ISO 4217 — بياناتٌ مرجعية، لا قرار.</b>
/// <para>
/// الرقمُ هنا ليس اختياراً يعود لصاحب المصلحة ولا لمحاسب: هو «الأُسّ» الذي تنشره
/// المعيارُ الدولية لكلّ عملة (القائمة الأولى من ISO 4217)، وبه يُعرَّف أصغرُ مبلغٍ
/// يمكن أن يُدفع فعلاً — الهللةُ للريال (خانتان)، والفلسُ للدينار الكويتي (ثلاث)،
/// ولا خانةَ للين الياباني. وما ليس اختياراً لا يُعرض في لوحة تحكّم كي «يُقرَّر»؛
/// لكنه أيضاً ليس رقماً يجوز أن يُكتب في حساب سطرٍ باسم «الهللة» مهما كانت عملة
/// المنشأة — وهو بالضبط ما كان في <c>LineMath.Halalas = 2</c> قبل ADR-0089.
/// </para>
/// <para>
/// <b>والجدولُ ناقصٌ عمداً وبإعلان:</b> فيه عملاتُ الخليج والعالم العربي وأكثرُ
/// عملات التجارة تداولاً. وعملةٌ ليست فيه <b>تُرفض عند التأسيس باسمها</b> مع علاجٍ
/// مسمّى — إضافةُ صفّها هنا بمرجعه من القائمة — لا تُخمَّن لها خانتان. فالتخمينُ
/// هو ما يجعل دينارَ البحرين يُقرَّب إلى الفلس الأعلى صامتاً في كلّ فاتورة.
/// </para>
/// <para>
/// <b>المرجع:</b> ISO 4217:2015 — «Codes for the representation of currencies»،
/// القائمة الأولى (العملات والأموال الجارية)، عمود «Minor unit». والقائمةُ تُصدرها
/// وكالة الصيانة (SIX) وتُعدَّل بتعميماتٍ مرقَّمة؛ وأيُّ تعديلٍ يخصّ صفّاً هنا يُنقل
/// بتعميمه لا بذاكرة.
/// </para>
/// </summary>
