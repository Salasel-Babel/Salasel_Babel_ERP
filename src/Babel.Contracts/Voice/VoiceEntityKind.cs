namespace Babel.Contracts.Voice;

/// <summary>
/// <b>السجلّ الذي تُسمّي الشريحةُ صفّاً منه</b> — لا صنفُ الكلمة ولا موقعُها من الإعراب.
/// <para>
/// <b>ولماذا هذا الوسم موجود أصلاً:</b> قارئ الكلام كان يُنهي اسم العميل عند أوّل كلمةٍ
/// يعرفها من قائمة إيقافٍ مكتوبة بيد. وقائمةُ إيقافٍ تحصر <b>ما ليس في الاسم</b>، أي
/// متمّمةَ مجموعةٍ مفتوحة — اللغةُ كلُّها إلا صفّاً واحداً. فأوّلُ أداةِ شرطٍ لم تُكتب
/// («فإن»، «لو»، «إذا ما»، «لين») تدخل الاسم بصمت، ويخرج مستندٌ صحيح الشكل باسمِ طرفٍ
/// لا وجود له. وهذا وقع فعلاً على شاشة صاحب المنتج في أوّل جملةٍ قالها للنظام الحيّ.
/// </para>
/// <para>
/// <b>والانقلاب الذي يمثّله هذا النوع:</b> الاسم ليس مقولةً لغوية، بل <b>صفٌّ في سجلّ</b>.
/// فمن يملك السجلّ يملك حدَّ الاسم — لا النحوُ الذي حوله. وشريحةٌ موسومة بسجلٍّ
/// تُحَدُّ بذلك السجلّ حين يكون حاضراً، و<b>تُرفض ولا تُخمَّن</b> حين لا يكون ولا يبلغها
/// حدٌّ آخر. والشريحةُ الموسومة <see cref="None"/> نثرٌ حرّ لا يسمّي صفّاً، فلا سجلّ
/// يحدّها ولا يُدّعى لها حدّ.
/// </para>
/// <para>
/// <b>وهي وسمٌ لا مرجع:</b> قيمةٌ في تعداد، لا اسمُ جدولٍ ولا مرجعٌ إلى وحدة. والوحدةُ
/// المالكة تُسهم بأسمائها عبر <see cref="IVoiceEntityDirectory"/> — بانقلاب الاعتماد
/// نفسه الذي تُسهم به بنيّاتها (القاعدة 3).
/// </para>
/// </summary>
public enum VoiceEntityKind
{
    /// <summary>
    /// لا سجلّ — <b>نثرٌ حرّ</b>: بيانُ قيدٍ، وسببُ أمرِ تغيير. لا يُدّعى له حدٌّ من سجلّ،
    /// ولا يُقاس بعرضِ اسم: إطالةُ نثرٍ إسهابٌ، وإطالةُ اسمٍ <b>طرفٌ آخر</b>.
    /// </summary>
    None = 0,

    /// <summary>سجلّ العملاء.</summary>
    Customer,

    /// <summary>سجلّ المورّدين.</summary>
    Supplier,

    /// <summary>سجلّ الموظفين.</summary>
    Employee,

    /// <summary>سجلّ الأصناف.</summary>
    Item,

    /// <summary>سجلّ المستودعات.</summary>
    Warehouse,

    /// <summary>سجلّ المشاريع.</summary>
    Project,

    /// <summary>سجلّ العقود — عقدُ عميلٍ أو عقدُ باطن.</summary>
    Contract,

    /// <summary>سجلّ مقاولي الباطن.</summary>
    Subcontractor,

    /// <summary>بنود جدول الكمّيات.</summary>
    BoqItem,

    /// <summary>سجلّ المستأجرين.</summary>
    Lessee,
}
