namespace Babel.Ai.Suggestions;

/// <summary>
/// اقتراح النموذج: <b>رمز حدث ودور</b> من مفردات مغلقة — <b>ولا رمز حساب أبداً</b>.
/// <para>
/// <b>لماذا لا يرى النموذج دليل حسابات المستأجر:</b> سببان يجتمعان على الجواب نفسه.
/// الأول تسرّب خصوصية — دليل حسابات المنشأة بنية أعمالها. والثاني أخطر: نموذج يرى
/// أسماء الحسابات <b>يخترع حساباً يبدو موجوداً</b>، ويُقبل الاقتراح لأنه معقول.
/// </para>
/// <para>
/// والمصفوفة — لا النموذج — هي التي تحوّل الحدث إلى حساب هذا المستأجر. وهذا هو نفسه
/// السبب الذي تقوم عليه القاعدة المعمارية 2: الوحدة تصف حدثاً، والمصفوفة تقرّر الحساب.
/// </para>
/// <para>
/// ورمزُ حدثٍ مخترَع ليس فرضية نظرية في هذا المستودع: رمزٌ خارج المصفوفة قيس وهو
/// يُنتج <b>ترحيلاً مكرَّراً صامتاً</b> (‏ADR-0016)، ولذلك يُرفض هنا قبل أن يصل إلى أحد.
/// </para>
/// </summary>
public sealed record PostingSuggestion
{
    /// <summary>رمز الحدث في مصفوفة الترحيل. معرّف لا يُترجَم (‏ADR-0021).</summary>
    public required string EventCode { get; init; }

    /// <summary>رمز الدور المحاسبي، أو فارغ. معرّف لا يُترجَم.</summary>
    public string RoleCode { get; init; } = string.Empty;

    /// <summary>درجة ثقة النموذج بين صفر وواحد. <c>decimal</c> لا <c>double</c>.</summary>
    public required decimal Confidence { get; init; }

    /// <summary>تعليل النموذج كما كتبه — سجلّ لا ترجمة، ولا يُعرض بديلاً عن قرار الإنسان.</summary>
    public string Rationale { get; init; } = string.Empty;
}
