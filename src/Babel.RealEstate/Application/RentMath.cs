namespace Babel.RealEstate.Application;

/// <summary>
/// حساب سطر الفاتورة العقارية.
/// <para>
/// <b>القاعدة المتّبعة هي قاعدة المستودع القائمة لا قاعدةً جديدة:</b> الضريبة تُحسب
/// وتُقرَّب <b>على مستوى السطر</b>، ومجموع المستند مجموع سطور مقرَّبة ولا يُعاد تقريبه
/// (‏<c>Babel.Sales.Application.LineMath</c> بنصّه). القلب — تقريب المجموع بعد جمع قيم
/// غير مقرَّبة — يُنتج فرق هللة على كل فاتورة تقريباً.
/// </para>
/// <para>
/// <b>وما لا يوجد هنا مقصود: لا توزيع لقيمة العقد على أقساط.</b> ذلك التوزيع يستلزم
/// سياسة تقريب — أين يقع فائض الهللات — وهي قرار مالك مفتوح (ق-ع-3). فالأقساط تصل
/// مصرَّحاً بها، وتُفحص أن مجموعها يساوي قيمة العقد بالضبط.
/// </para>
/// <para>
/// <b>ولا نسبة ضريبة مكتوبة هنا:</b> النسبة تصل مع الطلب، ولا رقم نظامي يُكتب في شيفرة.
/// </para>
/// </summary>
internal static class RentMath
{
    /// <summary>خانتان عشريتان: الهللة أصغر وحدة نقدية، والتقريب سياسة لا صدفة.</summary>
    private const int Halalas = 2;

    /// <summary>المعاملة الضريبية التي تُنتج توريداً خاضعاً.</summary>
    public const string Standard = "standard";

    /// <summary>يقرّب إلى الهللة، والنصف يبتعد عن الصفر.</summary>
    /// <param name="value">القيمة.</param>
    public static decimal Round(decimal value) => decimal.Round(value, Halalas, MidpointRounding.AwayFromZero);

    /// <summary>
    /// ضريبة سطرٍ صافيه معلوم، أو صفرٌ حين لا يكون التوريد خاضعاً.
    /// <para>
    /// <b>والخضوع يُحسم قبل هذه الدالّة لا فيها</b>، لأنه يختلف باختلاف نموذج الملكية:
    /// في الملكية الذاتية يكفي أن تكون معاملة الوحدة <c>standard</c>؛ وفي الإدارة يشترط
    /// القالب <b>أن يكون المالك مسجَّلاً ضريبياً كذلك</b> — والفاتورة صادرة لحسابه.
    /// وحسابُ ضريبةٍ لا يحمل القالب سطراً لها يُنتج <b>قيداً غير متوازن</b>: مدينٌ
    /// بالصافي والضريبة ودائنٌ بالصافي وحده، فيسقط عند COMMIT بلا سبب مفهوم.
    /// </para>
    /// </summary>
    /// <param name="net">صافي السطر.</param>
    /// <param name="taxRate">النسبة كسراً عشرياً كما وصلت مع الطلب.</param>
    /// <param name="taxable">هل التوريد خاضع؟ مُحسوماً من معاملة الوحدة ومن نموذج الملكية معاً.</param>
    public static decimal Tax(decimal net, decimal taxRate, bool taxable)
        => taxable ? Round(net * taxRate) : 0m;
}
