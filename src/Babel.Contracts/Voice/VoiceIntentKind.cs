namespace Babel.Contracts.Voice;

/// <summary>
/// صنف النيّة — <b>وهو ما يحدّد وحده هل تحتاج تأكيداً</b>.
/// <para>
/// ولا يُترك «هل يحتاج تأكيداً؟» حقلاً حرّاً يملؤه من يكتب النيّة: حقلٌ حرّ يُنسى
/// مرّةً واحدة فتُنفَّذ عملية تكتب في الدفتر بلا قراءةٍ مرتدّة. الصنف يُملي التأكيد،
/// والحارس يقيس أن كل نيّةٍ مُغيِّرة للحال تحمله.
/// </para>
/// </summary>
public enum VoiceIntentKind
{
    /// <summary>استعلام لا يكتب شيئاً — يُنفَّذ مباشرة.</summary>
    Query = 1,

    /// <summary>انتقالٌ إلى شاشة — يُنفَّذ مباشرة.</summary>
    Navigation = 2,

    /// <summary>
    /// تغييرٌ للحال: قيدٌ في الدفتر، أو حركةُ مخزون، أو صرفٌ لإنسان، أو توقيعُ عقد.
    /// <b>لا يُنفَّذ بلا تأكيدٍ صريح — بلا استثناء.</b>
    /// </summary>
    StateChange = 3,
}
