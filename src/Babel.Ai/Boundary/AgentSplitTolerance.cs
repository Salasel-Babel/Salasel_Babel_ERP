namespace Babel.Ai.Boundary;

/// <summary>
/// <b>كم يحتمل هذا الشكل من القطع؟</b> — والجواب ليس واحداً لكل الأشكال، ولا يجوز أن يكون.
/// <para>
/// المعرّف المقطوع معرّفٌ كامل عند من يقرؤه: <c>«1092 837465»</c> رقمُ هوية،
/// و<c>«SA03 8000 …»</c> آيبان. فلا بدّ من لمّ الفواصل قبل الفحص. <b>لكنّ اللمّ يخترع
/// سلاسل لم تُكتب</b>، ولذلك يُقنَّن بحسب <b>ارتكاز</b> الشكل:
/// </para>
/// <list type="bullet">
///   <item><b>مُرتكِز</b> (بادئة <c>SA</c> · بادئة <c>05</c>/<c>966</c> · خمس عشرة خانة
///         بين <c>3</c> و<c>3</c>): دليلُه في بنيته لا في طوله، فيحتمل اللمّ عبر
///         المسافات <b>والشرطات</b>.</item>
///   <item><b>مجرَّد</b> (عشر خانات وحدها — هوية أو سجلّ): دليلُه الطول وحده، فلا يحتمل
///         إلا لمّ المسافات. <c>INV-2026-000412</c> رقمُ فاتورة يوميّ، ولمّ شرطاته
///         يجعله «هوية».</item>
///   <item><b>الشامل والقناع</b>: لا لمّ إطلاقاً. بعد اللمّ يصير «الطول» دليلاً يُنتجه
///         النثر نفسه، فيُرفض كلامٌ سليم كل يوم — وحارسٌ يُرفض به السليمُ يُعطَّل.</item>
/// </list>
/// </summary>
public enum AgentSplitTolerance
{
    /// <summary>لا يُعاد الفحص على نصٍّ ملموم.</summary>
    None = 1,

    /// <summary>يُعاد الفحص بعد لمّ المسافات بأنواعها.</summary>
    Whitespace = 2,

    /// <summary>يُعاد الفحص بعد لمّ المسافات والشرطات — للأشكال المُرتكِزة وحدها.</summary>
    WhitespaceAndDashes = 3,
}
