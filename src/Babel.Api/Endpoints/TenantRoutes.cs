namespace Babel.Api.Endpoints;

/// <summary>
/// مسارات التسجيل والاشتراك، معلنة مرّة واحدة — كما في <see cref="ApiRoutes"/> و
/// <see cref="AccessRoutes"/>، وفي ملفٍّ مستقلّ للسبب نفسه: ملفُّ المسارات هو الموضع
/// الذي يتصادم فيه فرعان بلا داعٍ.
/// <para>
/// <b>وهذه المسارات خارج نطاق المنشأة عمداً:</b> المستأجر <b>فوق</b> المنشأة لا داخلها،
/// ومن يشترك لأول مرّة لا يملك منشأةً يضع معرّفها في المسار. والنطاق مع ذلك مفروض:
/// كل مسار تحت <c>{tenantId}</c> يُطابَق بمستأجر الاعتماد ويُرفض إن اختلف — ولا يُفرَّق
/// في الرفض بين «لا وجود له» و«ليس مستأجرك»، فذلك يجعل السطح عدّاد وجود.
/// </para>
/// <para>
/// <b>ولماذا <c>/tenants</c> هنا وقد قال ADR-0045 §3 إن إنشاء المستأجر ليس على
/// <c>/api/v1</c>:</b> ذاك القرار رفض أن <b>ينفَّذ</b> إنشاء المستأجر في مستوى المستأجر،
/// وهو رفضٌ قائم — التنفيذ ما يزال كلّه في <c>Babel.ControlPlane</c>. وما تغيّر أن
/// الفعل صار له <b>باب</b> على السطح المنشور، والجذر التركيبي وحده يعبر بينهما.
/// وبلا هذا الباب لا يستطيع أحد أن يشترك في منتَجٍ يُباع بالاشتراك (ADR-0050).
/// </para>
/// </summary>
internal static class TenantRoutes
{
    /// <summary>
    /// التسجيل الأول: إنشاء مستأجر وأول عضوية مالكة. <b>بلا مصادقة</b>، و<b>حصينٌ ضد
    /// التكرار</b> بمفتاح الطلب.
    /// </summary>
    public const string Tenants = ApiRoutes.Base + "/tenants";

    /// <summary>نطاق المستأجر. لا مسار تحته يُخدَم لاعتماد مستأجرٍ آخر.</summary>
    public const string Tenant = Tenants + "/{tenantId}";

    /// <summary>
    /// اشتراك المستأجر: الخطّة والحالة والوحدات المُستحَقّة وتاريخ التجديد.
    /// <para>
    /// مورد واحد لا موردان: الاشتراك كلٌّ يُقرأ في طلب واحد. وتفريقه على «خطّة» و«حالة»
    /// و«وحدات» كان سيجعل «هل أستطيع أن أُرحّل اليوم؟» سؤالاً يُجاب بتجميع ثلاثة طلبات
    /// تُقرأ في ثلاث لحظات مختلفة.
    /// </para>
    /// </summary>
    public const string Subscription = Tenant + "/subscription";

    /// <summary>
    /// تغيير الخطّة. <b>مورد فرعي مستقلّ، لا <c>PUT</c> على الاشتراك:</b> تغيير الخطّة
    /// <b>حدثٌ</b> له سندٌ وفاعلٌ ولحظة، ويُغلق صفّ اشتراك ويفتح آخر. و<c>PUT</c> كان
    /// سيقول إن الاشتراك مستندٌ يُستبدل، فيضيع تاريخُه ويصير «على أي خطّة كان في مارس؟»
    /// سؤالاً بلا جواب.
    /// </summary>
    public const string SubscriptionPlanChanges = Subscription + "/plan-changes";

    /// <summary>
    /// انقطاع الاشتراك. مورد فرعي مستقلّ على نمط إيقاف مركز التكلفة: الانقطاع حالةٌ
    /// تُطلب بسندٍ مكتوب، لا حقلٌ يُعدَّل.
    /// <para>
    /// <b>وما لا يفعله:</b> لا يحجب القراءة ولا يُنتزع سجلّ. الوحدات تهبط إلى
    /// <b>أرضيتها</b> — قراءةً وتقارير وتصديراً كاملة (ADR-0034).
    /// </para>
    /// </summary>
    public const string SubscriptionLapse = Subscription + "/lapse";

    /// <summary>استئناف الاشتراك بعد انقطاعه — مورد فرعي مستقلّ بالشكل نفسه.</summary>
    public const string SubscriptionResumption = Subscription + "/resumption";
}
