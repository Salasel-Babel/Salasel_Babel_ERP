        409 => "تعارض مع حالة قائمة: المستند ليس في الحالة التي يقبلها هذا الفعل، أو الفترة مقفلة.",
        422 => "الطلب مفهوم ومرفوض محاسبياً: تجاوز حدّ ائتمان، أو تخصيص يتجاوز المتبقّي، أو دور لا يُحلّ إلى حساب.",
        _ => "رفض.",
    };

    private static string ProblemEn(int status) => status switch
    {
        404 => "The resource does not exist within this company's scope.",
        409 => "Conflict with existing state: the document is not in a state this act accepts, or the period is closed.",
        422 => "Understood and refused on accounting grounds: a credit limit exceeded, an allocation beyond what is outstanding, or a role that resolves to no account.",
        _ => "Refused.",
    };

    private static void WriteResponse(
        Utf8JsonWriter w, int status, string ar, string en, string schema,
        string mediaType = "application/json", string? inlineType = null, string? inlineFormat = null)
    {
        w.WriteStartObject(status.ToString(System.Globalization.CultureInfo.InvariantCulture));
        w.WriteString("description", ar + " / " + en);
        w.WriteStartObject("content");
        w.WriteStartObject(mediaType);

        if (inlineType is null)
        {
            WriteRef(w, "schema", schema);
        }
        else
        {
            // شكلٌ مضمَّن لا مرجع: البابان الساكنان يخدمان ملفَّين، ولا يوجد نموذج مجال
            // يُسمّى لهما. واختراع مخطّط باسمٍ لأحدهما كان سيضع في العقد اسماً لا يقابله
            // نوع في الشيفرة — وهو أول انفصال بين العقد وما يولّده.
            w.WriteStartObject("schema");
            w.WriteString("type", inlineType);
            if (inlineFormat is not null)
            {
                w.WriteString("format", inlineFormat);
            }

            w.WriteEndObject();
        }

        w.WriteEndObject();
        w.WriteEndObject();
        w.WriteEndObject();
    }

