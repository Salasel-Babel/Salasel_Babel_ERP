namespace Babel.Api.Endpoints;

/// <summary>
/// مسارات سطح المصادقة والعضوية، معلنة مرّة واحدة — كما في <see cref="ApiRoutes"/>.
/// <para>
/// وهي في ملفٍّ مستقلّ لا في ذاك عمداً: هذا السطح وُلد على فرعٍ متوازٍ لفرعٍ آخر يضيف
/// نقاط نهاية، وملفُّ المسارات هو الموضع الذي يتصادم فيه فرعان بلا داعٍ. والفصلُ لا
/// يُنشئ مصدر حقيقة ثانياً: كل مسار هنا يُكتب مرّة واحدة، ويقرؤه التسجيل والمولّد
/// والاختبار من هذا الملفّ وحده.
/// </para>
/// <para>
/// <b>ولاحظ أين وقعت الحدود:</b> ما تحت <c>/access/</c> <b>خارج نطاق المنشأة</b> — ومن
/// لا جلسة له لا يعرف معرّف منشأته ليضعه في المسار — و<b>العضوية داخله</b>، لأن دعوة
/// عضوٍ فعلٌ <b>في منشأة بعينها</b> ويجب أن يمرّ بالمطابقة نفسها التي يمرّ بها كل مسار
/// آخر: اعتمادٌ لا يبلغ المنشأة يُرفض بـ<c>tenancy.company_out_of_scope</c> ولا يُسرَّب
/// عنها شيء.
/// </para>
/// <para>
/// <b>وما ليس هنا: مسار «إنشاء مستأجر».</b> وغيابه بنيوي لا سهو — التزويد يقع في
/// <c>Babel.ControlPlane</c> <b>فوق</b> الأسطول، وهو مُعلَن في <c>ModuleMap</c> بلا
/// مرجعية إليه ولا منه (‏ADR-0036 §2). والحجّة كاملةً في قرار هذا الفرع.
/// </para>
/// </summary>
internal static class AccessRoutes
{
    /// <summary>جذر سطح المصادقة — خارج نطاق المنشأة، كنقطة الجلسة.</summary>
    public const string Base = ApiRoutes.Base + "/access";

    /// <summary>فتح جلسة باعتماد انتساب. <b>بلا مصادقة</b> — وهو الباب الذي تُكتسب منه.</summary>
    public const string Sessions = Base + "/sessions";

    /// <summary>
    /// تجديد جلسة بتدوير اعتمادها. مورد فرعي مستقلّ: التجديد فعلٌ يُنشئ اعتماداً جديداً،
    /// لا تعديلٌ على اعتماد قائم — والاعتماد القديم يُستهلك ولا يُعدَّل.
    /// </summary>
    public const string SessionRenewal = Sessions + "/renewal";

    /// <summary>
    /// إبطال الجلسة الجارية. مورد فرعي مستقلّ على نمط إيقاف مركز التكلفة: الإبطال حالةٌ
    /// تُطلب، لا حقلٌ يُعدَّل. و<b>لا فعل حذف هنا</b> كما لا فعل حذف في أي موضع من هذا السطح.
    /// </summary>
    public const string SessionRevocation = Sessions + "/revocation";

    /// <summary>
    /// أعضاء المنشأة: القائمة، والدعوة.
    /// <para>
    /// <b>وهي داخل نطاق المنشأة عمداً:</b> «من يعمل في هذه المنشأة» سؤالٌ عن منشأة،
    /// وجوابُه بيانات مستأجر. ووضعُه خارج النطاق كان سيُنشئ باباً ثانياً إلى بيانات
    /// المستأجرين لا يمرّ بالمطابقة التي يمرّ بها كل باب غيره.
    /// </para>
    /// </summary>
    public const string Memberships = ApiRoutes.Company + "/memberships";

    /// <summary>
    /// عضوية واحدة داخل المنشأة.
    /// <para>
    /// <b>ومعرّف العضوية هو معرّف عضوها</b>، ويُقال ذلك صراحةً بدل أن يُترك يُفهَم:
    /// هوية العضوية هي <c>(المنشأة، العضو)</c> — وهو مفتاحها الأوّلي في قاعدة البيانات
    /// حرفياً — والمنشأة في المسار سلفاً، فلم يبقَ منها ما يُعنون غير العضو. واختراعُ
    /// مفتاحٍ بديل كان سيُنتج <b>هويتين لصفٍّ واحد</b>: العميل يقرأ العضو من قائمة
    /// الأعضاء ثم يحتاج معرّفاً ثانياً لا يعرف من أين يأتي.
    /// </para>
    /// </summary>
    public const string Membership = Memberships + "/{membershipId}";

    /// <summary>
    /// سحب عضوية. مورد فرعي مستقلّ لا <c>DELETE</c> على العضوية: السحب <b>فعلٌ له فاعل
    /// ولحظة ويُكتب في سجلّ التدقيق</b>، و<c>DELETE</c> كان سيقوله «أزل صفّاً».
    /// <para>
    /// <b>ولا يُسحب آخر مالك:</b> منشأةٌ بلا مالك لا يستطيع أحد أن يدعو إليها ولا أن
    /// يُصلح أدوارها — أي بيانات محبوسة عن أصحابها بفعلٍ يبدو إدارياً.
    /// </para>
    /// </summary>
    public const string MembershipRevocation = Membership + "/revocation";

    /// <summary>
    /// تغيير دور عضوية. مورد فرعي مستقلّ على نمط <c>plan-changes</c>: الدور صلاحيةُ
    /// وصول، وتغييرُه حدثٌ لا حقلٌ يُعدَّل بتحديث جزئي.
    /// </summary>
    public const string MembershipRoleChanges = Membership + "/role-changes";
}
