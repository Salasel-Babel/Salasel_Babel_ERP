    /// <summary>
    /// عددُ خانات الوحدة الصغرى لعملةٍ كما تنصّ القائمة، أو <c>null</c> إن لم تكن
    /// العملةُ في الجدول — <b>ولا تخمين</b>: الغائبُ يُرفض باسمه عند المستدعي.
    /// </summary>
    /// <param name="currency">رمز العملة.</param>
    public static int? MinorUnitsOf(CurrencyCode currency)
        => currency.IsAssigned && MinorUnitsByCode.TryGetValue(currency.Value, out int units) ? units : null;

    /// <summary>هل العملةُ في الجدول؟</summary>
    /// <param name="currency">رمز العملة.</param>
    public static bool IsKnown(CurrencyCode currency) => MinorUnitsOf(currency) is not null;

