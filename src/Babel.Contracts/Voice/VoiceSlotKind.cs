namespace Babel.Contracts.Voice;

/// <summary>
/// صنف الشريحة — <b>وهو ما يقرّر كيف تُقرأ وكيف تُرفض</b>.
/// <para>
/// <b>ولماذا <see cref="Quantity"/> صنفٌ مستقلّ عن <see cref="Number"/>:</b> لأن الكمّية
/// بلا وحدة ليست كمّية. «عشرين» في مستودعٍ فيه الصنف بالحبّة والعلبة والكرتون عددٌ
/// لا معنى له، وفرقُ التفسير بينها اثنا عشر ضعفاً. فالوحدة جزء من القيمة لا زينة
/// بجانبها، وغيابُها رفضٌ مُسمّى لا افتراضُ وحدة الأساس.
/// </para>
/// </summary>
public enum VoiceSlotKind
{
    /// <summary>
    /// <b>اسم طرفٍ يُحلّ في سجلٍّ محلّي — ولا يصير قيمةً بنصّه أبداً.</b>
    /// <para>
    /// وهي الشريحة التي أنتجت العطل الذي أُغلق بهذا التحويل: قارئٌ يقرّر <b>أين ينتهي
    /// الاسم</b> بقواعد إيقافٍ يخترعها من الجملة يُنتج طرفاً آخر صحيح الشكل. فصار القارئ
    /// يحمل <b>المقطع كما سُمع</b> ولا يقرّر، والسجلّ هو الذي يجيب: لا شيء · واحد · سؤال.
    /// وقيمةُ هذه الشريحة في الأمر المُصرَّح به <b>مِقبضٌ معتم</b> لا نصّ.
    /// </para>
    /// <para>
    /// وكلُّ شريحةٍ من هذا الصنف <b>تُسمّي سجلَّها</b> (<c>VoiceSlot.RegisterKey</c>)، وغيابُه
    /// يُسقط <b>بناء</b> السجلّ لا نُطقاً واحداً.
    /// </para>
    /// </summary>
    Entity = 1,

    /// <summary>عدد مجرّد يُقرأ بقاموس الأعداد المنطوقة المغلق.</summary>
    Number = 2,

    /// <summary>مبلغ مالي. <b>نصّ على السلك دائماً</b> ولا يصير عائمة في أي طبقة.</summary>
    Money = 3,

    /// <summary>كمّية <b>ووحدتها معاً</b>. أحدهما بلا الآخر رفض.</summary>
    Quantity = 4,

    /// <summary>تاريخ ميلادي بصيغة ISO.</summary>
    Date = 5,

    /// <summary>رمزٌ أو رقم مستند كما نُطق.</summary>
    Code = 6,

    /// <summary>اختيار من قائمة مغلقة تُعلنها الشريحة. ما ليس فيها مرفوض.</summary>
    Choice = 7,

    /// <summary>
    /// <b>نصٌّ حرّ لا يُسمّي أحداً</b> — «بيان القيد» و«سبب التغيير».
    /// <para>
    /// <b>وهو يحتفظ بالقاعدة التقريبية عمداً، والتباين يُقال صراحةً:</b> بيانٌ خاطئ سطرٌ
    /// تجميليّ يقرؤه إنسان على شاشة المسوّدة؛ وعميلٌ خاطئ <b>طرفٌ آخر</b> على مستندٍ
    /// يُرحَّل. والفرق بين الاثنين ليس في الدقّة بل في الثمن.
    /// </para>
    /// <para>
    /// وحارسٌ في <c>NoDraftIsBuiltFromASpokenName</c> يقيس أن لا شريحة من هذا الصنف تُغذّي
    /// حقلَ معرّفٍ في العقد المنشور، فلا يلتبس الصنفان ثانيةً.
    /// </para>
    /// </summary>
    Prose = 8,
}
