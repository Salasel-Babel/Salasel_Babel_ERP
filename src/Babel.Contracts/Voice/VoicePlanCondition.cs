namespace Babel.Contracts.Voice;

/// <summary>
/// شرطُ تنفيذ خطوةٍ في خطّة. <b>وقائمةٌ مغلقة بقصد</b>: شرطٌ حرّ يُكتب نصّاً يصير
/// لغةً صغيرة داخل بيانات، ولغةٌ صغيرة بلا مصرِّف تُخطئ بصمت.
/// </summary>
public enum VoicePlanCondition
{
    /// <summary>تُنفَّذ دائماً.</summary>
    Always = 1,

    /// <summary>
    /// <b>تُنفَّذ حين يقول الإنسان إنه لم يجد ما بحث عنه.</b>
    /// <para>
    /// <b>ولماذا «يقول الإنسان» لا «لم يجد النظام»:</b> لا يستطيع المسار المنطوق أن
    /// يبحث. لا ينادي باباً منشوراً (‏<c>handoff.ts</c>)، ولا يوجد في العقد المنشور
    /// بحثٌ عن عميلٍ بالاسم أصلاً — <c>readCustomer</c> يطلب معرّفاً، ولا
    /// <c>listCustomers</c>. <b>والوحيد في هذه المعمارية القادر على حلّ اسمٍ إلى
    /// هويّة هو الإنسان أمام شاشةٍ فيها مُنتقٍ</b>، وهو الذي يحلّه أصلاً في كل مسوّدة.
    /// </para>
    /// <para>
    /// فتسميةُ هذا الشرط «حين لا يجد النظام» كانت ستكون <b>كذبةً في نظام الأنواع</b>:
    /// تَعِد ببحثٍ لا يقع، وتُخفي أن الجواب جاء من فم إنسان. والاسمُ يقول من أين جاء
    /// الجواب، فيبقى «لا يُخترَع» صحيحاً على الخطّة كما هو صحيح على الشريحة.
    /// </para>
    /// </summary>
    WhenHumanFindsNothing = 2,
}
