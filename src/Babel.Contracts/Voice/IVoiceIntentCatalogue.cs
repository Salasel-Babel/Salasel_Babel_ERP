using Babel.SharedKernel;

namespace Babel.Contracts.Voice;

/// <summary>
/// ما تُسهم به وحدةٌ من نيّات منطوقة. <b>الوحدة تُعلن نيّاتها، ولا يعرفها أحد بالاسم.</b>
/// <para>
/// <b>وهذا هو انقلاب الاعتماد بعينه:</b> لولاه لَاحتاجت وحدة الذكاء — وهي وحدةٌ أفقية —
/// مرجعاً إلى المخزون والموارد البشرية والعقارات لتعرف نيّاتها، وهو ما تمنعه القاعدة 3.
/// وبه صارت إضافةُ نيّةٍ جديدة <b>لا تمسّ مشروع الذكاء بسطر</b>: تُكتب في الوحدة
/// المالكة، وتُسجَّل عند تسجيلها، ويلتقطها السجلّ من الحاوية.
/// </para>
/// </summary>
public interface IVoiceIntentCatalogue
{
    /// <summary>الوحدة المالكة لهذه المجموعة.</summary>
    BabelModule Module { get; }

    /// <summary>نيّاتها. <b>مغلقة</b>: ما ليس فيها لا يُنطَق ولا يُخمَّن.</summary>
    IReadOnlyList<VoiceIntent> Intents { get; }
}
