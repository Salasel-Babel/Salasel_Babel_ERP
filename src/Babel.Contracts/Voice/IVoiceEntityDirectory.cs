using Babel.SharedKernel;

namespace Babel.Contracts.Voice;

/// <summary>
/// <b>ما تُسهم به وحدةٌ من أسماءٍ مسجَّلة</b> — نظير <see cref="IVoiceIntentCatalogue"/>
/// مبدأً ودليلاً واتجاهَ اعتماد.
/// <para>
/// <b>وهو الانقلاب نفسه:</b> لولاه لَاحتاجت وحدةُ الذكاء — وهي وحدةٌ أفقية — مرجعاً إلى
/// المبيعات لتعرف عملاءها وإلى المخزون ليعرف أصنافه، وهو ما تمنعه القاعدة 3. فالوحدة
/// تُعلن أسماءها، و<b>لا يعرفها هذا المشروع بالاسم</b>؛ ويقرأ القارئُ العقدَ وحده.
/// </para>
/// <para>
/// <b>وما يفعله هذا الدليل بالضبط:</b> يحدّ <b>طرفَ الاسم</b> في الكلام. القارئ يأخذ
/// النافذة من دليل الشريحة إلى أوّل حدٍّ، ويسأل: أيُّ اسمٍ مسجَّل هو <b>بادئةُ</b> هذه
/// النافذة؟ فينتهي الاسم حيث ينتهي الصفُّ المسجَّل — لا حيث تصادف أن جاءت أداةُ عطف.
/// وما بقي من النافذة بعده <b>يُسمّى فضلةً ويُقال</b>، ولا يُبتلع في الاسم ولا يُلقى.
/// </para>
/// <para>
/// <b>وثلاثة أشياء لا يفعلها:</b> لا يُقارِب اسماً بأقرب شبيه — فتقريبٌ في اسم طرفٍ
/// يُنتج مستنداً صحيح الشكل على طرفٍ آخر؛ ولا يختار بين اسمين متساويَي الطول — بل
/// <b>يُرفض التعادل</b> كما تُرفض النيّتان المتعادلتان؛ ولا يحمل رقم حساب — والقاعدة 2
/// مفروضة عند البناء لا موصوفة.
/// </para>
/// </summary>
public interface IVoiceEntityDirectory
{
    /// <summary>الوحدة المالكة لهذه الأسماء.</summary>
    BabelModule Module { get; }

    /// <summary>السجلّ الذي تنتمي إليه.</summary>
    VoiceEntityKind Kind { get; }

    /// <summary>
    /// الأسماء <b>كما سُجّلت</b> — بإملائها الذي يُعرض ويُحفَظ، لا مطويّةً. والمطابقة
    /// تطوي، والحفظُ يبقي الأمين (‏<c>VoiceText</c>).
    /// </summary>
    IReadOnlyList<string> Names { get; }
}
