namespace Babel.Api.Endpoints;

/// <summary>
/// مسارات مساحة عمل الوكيل — <b>سطحٌ واحد لميزةٍ واحدة، لا ميزةٌ مبعثرة على الشاشات</b>.
/// <para>
/// <b>ولاحظ ما ليس في هذه القائمة ولا يجوز أن يوجد: مسار ترحيل.</b> غيابه بنيوي لا
/// اتفاقي، وبأربع طبقاتٍ كلٌّ منها كافية وحدها: الكتالوج المعروض على النموذج يُرشَّح عند
/// التركيب فيُسقطه إن حمل عملية ترحيل؛ و<c>AgentToolGate</c> يُعيد الفحص قبل كل تنفيذ؛
/// و<c>AgentDraftConfirmationGate</c> يرفض كل عمليةٍ فعلُها ليس <c>draft</c> قبل أن
/// يُسأل إنسان؛ ولا عملية <c>post…</c> في كتالوج الأدوات أصلاً.
/// </para>
/// <para>
/// <b>ولاحظ ما ليس فيها كذلك: مسار «مفتاح النموذج».</b> المفتاح لا يبلغ المتصفّح البتّة —
/// المتصفّح يكلّم هذا السطح، وهذا السطح يكلّم النموذج، والمفتاح متغيّر بيئةٍ على الخادم
/// يُسمّى بالاسم ولا يُقرأ في أي جسم.
/// </para>
/// </summary>
internal static class AgentRoutes
{
    /// <summary>
    /// جلسات مساحة العمل: الفتح.
    /// <para>
    /// <b>وداخل نطاق الشركة كأي مسارٍ آخر</b>: المنشأة من الاعتماد، والشركة من المسار،
    /// والجلسة تُنشأ مربوطةً بهما وبالمستخدم — وثلاثتها داخل بايتات كل مِقبضٍ تصدره
    /// هذه الجلسة، فمِقبضٌ من محادثةٍ لا يُفكّ في أخرى.
    /// </para>
    /// </summary>
    public const string Sessions = ApiRoutes.Company + "/agent/sessions";

    /// <summary>
    /// جلسةٌ واحدة: <b>قراءة حالها كلِّه</b> — الطور، والخطّة بخطواتها، وما ينتظر
    /// تأكيداً، وورقة السؤال المعلَّقة، ومؤشّر آخر حدث.
    /// <para>
    /// <b>مورد واحد لا أربعة، والسبب هو سبب <c>capability-profile</c> نفسه</b>: «ما
    /// الحال الآن؟» سؤالٌ يُجاب بطلبٍ واحد. وأربعةُ موارد كانت ستجعل لوحةً تُعيد الاتصال
    /// بعد انقطاعٍ تُصدر أربعة طلبات تصل بترتيبٍ لا يضمنه أحد، فتعرض خطّةَ دورٍ وتأكيدَ
    /// دورٍ آخر معاً.
    /// </para>
    /// <para>
    /// <b>ولا مسار حذف</b>: الجلسة تنقضي بخمولها، ولا تُمحى بيد — ومسار حذفٍ على مورد
    /// يحمل نسخة محادثةٍ كان سيَعِد بمحوٍ لا يبلغ ما نُسخ منه.
    /// </para>
    /// </summary>
    public const string Session = Sessions + "/{agentSessionId}";

    /// <summary>رسالةٌ من المستخدم: تبدأ دوراً وتعود بمعرّفه <b>فوراً</b> ولا تنتظر انتهاءه.</summary>
    public const string Messages = Session + "/messages";

    /// <summary>
    /// أحداث الدور بعد مؤشّر — <b>وهي بثُّ اللوحة</b>.
    /// <para>
    /// <b>ومؤشّرٌ لا دفقٌ مفتوح، وذلك قرارٌ لا تقصير:</b> النموذج يبثّ فعلاً، واللوحة
    /// يجب أن ترى تقدّماً لا صمتاً؛ لكن الدور يقف عند إنسانٍ مرّةً أو مرّتين وقد يمتدّ
    /// دقائق، ودفقٌ مفتوح يُقطَع عند أوّل وسيطٍ في الطريق فتُبنى فوقه آليةُ استئنافٍ
    /// ثانية. والمؤشّر يجعل الاستئناف هو الآلية الأولى نفسها: «ما بعد ن؟».
    /// </para>
    /// </summary>
    public const string Events = Session + "/events";

    /// <summary>
    /// تأكيد خطوة. <b>مورد فرعي مستقلّ</b> بسابقة <c>…/suspension</c> و<c>…/withdrawal</c>.
    /// <para>
    /// <b>ومعناه واحدٌ لا ثانيَ له: «أقبل شكل هذه البيانات».</b> ولا يعني الترحيل — والناتج
    /// بعده مسوّدةٌ كما كان قبله، والترحيل فعلٌ بصريّ يدويّ على شاشة المستند.
    /// </para>
    /// </summary>
    public const string StepConfirmation = Session + "/steps/{stepId}/confirmation";

    /// <summary>
    /// جواب ورقة السؤال.
    /// <para>
    /// <b>ومعرّف الورقة في الجسم لا في المسار</b>: هو مِقبضٌ معمّى بطولٍ ثابت من مئةٍ
    /// واثنين وخمسين محرفاً، ومقطعُ مسارٍ بهذا الطول يدخل سجلّات الوسطاء ويظهر في
    /// ترويسة المُحيل. والجسم <c>{questionId, optionToken}</c> — <b>مفتاحان لا ثالث
    /// لهما</b>، وهو الشكل نفسه الذي يبنيه المتصفّح في <c>web/src/agent/sheet.ts</c>.
    /// </para>
    /// </summary>
    public const string Answers = Session + "/answers";

    /// <summary>
    /// إنفاق المنشأة في نافذتها الجارية — <b>بالرموز لا بالريالات</b>.
    /// <para>
    /// خارج مورد الجلسة عمداً: الإنفاق يخصّ <b>المنشأة</b> لا محادثةً بعينها، ويُقرأ
    /// قبل أن تُفتح أي جلسة. ووضعُه تحت الجلسة كان سيجعل «كم أنفقتُ؟» سؤالاً لا يُسأل
    /// إلا بعد بدء حديثٍ جديد.
    /// </para>
    /// </summary>
    public const string Spend = ApiRoutes.Company + "/agent/spend";
}
