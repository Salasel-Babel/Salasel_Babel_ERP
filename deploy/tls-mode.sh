#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
# ‏**حارس أوضاع TLS** — يقرأ ما قرّره المالك، ويرفض ما لا تُستوفى شروطه،
# ويشتقّ ما لا يجوز أن يُكتب مرّتين.
#
# **المبدأ الذي يجسّده هذا الملف: يُرفض ولا يُخمَّن.** لا يهبط وضعٌ مطلوب إلى
# وضعٍ أضعف بصمت أبداً — لأن الهبوط من شهادة موثوقة إلى غير موثوقة هو بالضبط
# العطل الذي لا يستطيع المستخدم رؤيته: الصفحة تُفتح، والقفل مكسور، ولا سطر
# واحد في سجلّ النشر يقول إن شيئاً تغيّر.
#
# **ولماذا ملفٌّ لا سطورٌ داخل YAML:** منطقٌ داخل سير عمل لا يُشغَّل إلا بدفعة
# كاملة إلى خادم حقيقي، فلا يُجرَّب ولا يُختبَر — وهو السبب نفسه الذي أخرج
# `remote.sh` من YAML. وجدول حالاته في `tls-mode-check.sh` بجانبه.
#
#   المدخلات (بيئة): BABEL_TLS_MODE · BABEL_SITE · BABEL_TLS_EMAIL
#   المُخرَج (stdout): قيمة BABEL_TLS_IP — العنوان العارٍ في وضع `ip`، وفارغة
#                     في غيره. وهي ما يصير `default_sni` في Caddyfile.
#   الخروج: 0 إن استُوفيت الشروط · 1 مع رسالة تسمّي الناقص بالضبط.
#
# والأوضاع الأربعة وجدول موازنتها في `deploy/README.md §3`.
# ═══════════════════════════════════════════════════════════════════════════
set -euo pipefail

mode="${BABEL_TLS_MODE:-auto}"
site="${BABEL_SITE:-}"
email="${BABEL_TLS_EMAIL:-}"

fail() {
    while [ $# -gt 0 ]; do printf '::error::%s\n' "$1" >&2; shift; done
    exit 1
}

# ── ١ · الوضع نفسه معروف ────────────────────────────────────────────────────
# قيمةٌ مجهولة تجعل سطر `import tls-…` في Caddyfile يفشل **على الخادم** بعد أن
# تكون الحزمة القديمة قد أُوقفت — أي انقطاعٌ سببه خطأ مطبعي في متغيّر.
case "$mode" in
    auto | internal | ip) ;;
    *) fail "‏BABEL_TLS_MODE=«$mode» ليس وضعاً معروفاً — الأوضاع: auto · ip · internal." \
            "الجدول في deploy/README.md §3." ;;
esac

if [ -z "$site" ]; then
    fail "‏BABEL_SITE غير مضبوط. الجدول في deploy/README.md §1.1."
fi

# ── ٢ · الجزء المضيف من الموقع ──────────────────────────────────────────────
# ‏`:80` عنوان استماع بلا مضيف، ويُميَّز أولاً كي لا يُقرأ عنواناً (‏`:80` يطابق
# أشكال IPv6 الساذجة).
site_host=""
if [ "${site#:}" = "$site" ]; then
    site_host="${site#https://}"
    site_host="${site_host#http://}"
    site_host="${site_host%%/*}"
fi

# عنوان IPv4، أو IPv6 **بأقواس** — والأقواس إلزامية لأنها ما يجعل التمييز عن
# «مضيف:منفذ» ممكناً أصلاً.
ipv4_re='^((25[0-5]|2[0-4][0-9]|1[0-9][0-9]|[1-9]?[0-9])\.){3}(25[0-5]|2[0-4][0-9]|1[0-9][0-9]|[1-9]?[0-9])$'
site_is_ip=0
site_ip=""
if printf '%s' "$site_host" | grep -qE "$ipv4_re"; then
    site_is_ip=1
    site_ip="$site_host"
elif printf '%s' "$site_host" | grep -qE '^\[[0-9a-fA-F:]+:[0-9a-fA-F:]+\]$'; then
    site_is_ip=1
    site_ip="${site_host#[}"
    site_ip="${site_ip%]}"
fi

# ── ٣ · `auto` بعنوان IP: يبدو أنه يعمل، ولا يعمل ───────────────────────────
# ‏Caddy عند غياب مُصدِر صريح يُسنِد كل موضوع من نوع IP إلى **سلطته الداخلية**
# لا إلى Let's Encrypt، فتُصدَر شهادة موقّعة ذاتياً و**لا سطر تحذير واحد** في
# السجلّ: يقرأ سجلّ النشر أخضر، ويقرأ الضيف «غير آمن». المقصود `ip` لا `auto`.
if [ "$mode" = "auto" ] && [ "$site_is_ip" = "1" ]; then
    fail "‏BABEL_TLS_MODE=auto مع عنوان IP «$site_host» يُنتج شهادة **غير موثوقة** بصمت." \
         "للشهادة العامة على عنوان: BABEL_TLS_MODE=ip. وللسلطة الداخلية: BABEL_TLS_MODE=internal." \
         "الجدول في deploy/README.md §3."
fi

# ── ٤ · `auto` بنطاق حقيقي يتّصل بسلطة شهادات، وهي تطلب بريداً ───────────────
# وبريدٌ ناقص هنا يظهر لاحقاً بصفحةٍ لا تُفتح أمام الضيف — فيُرفض النشر الآن.
if [ "$mode" = "auto" ] && [ "${site#:}" = "$site" ] && [ -z "$email" ]; then
    fail "‏BABEL_TLS_MODE=auto بنطاق «$site» يتطلّب BABEL_TLS_EMAIL." \
         "إمّا أن تضبطه، أو تنتقل إلى BABEL_TLS_MODE=internal — راجع deploy/README.md §3."
fi

# ── ٥ · شروط وضع `ip` — أربعة، ولا يُنشَر بنقص واحد منها ────────────────────
tls_ip=""
if [ "$mode" = "ip" ]; then
    # (أ) الموقع عنوانٌ عارٍ.
    if [ "$site_is_ip" != "1" ]; then
        fail "‏BABEL_TLS_MODE=ip يتطلّب BABEL_SITE عنواناً عارياً: «https://203.0.113.10» أو «https://[2001:db8::1]»." \
             "والوارد «$site». وللنطاق استعمل BABEL_TLS_MODE=auto — deploy/README.md §3."
    fi

    # (ب) والمخطّط `https://` صريح: هو ما يجعل Caddy يستقبل على 443 ويشغّل
    #     الإصدار التلقائي، بدل أن يخمّن من شكل العنوان.
    if [ "${site#https://}" = "$site" ]; then
        fail "‏BABEL_TLS_MODE=ip يتطلّب أن يبدأ BABEL_SITE بـ«https://» صراحةً. الوارد «$site»."
    fi

    # (ج) والعنوان عامّ. سلطة الشهادات لا تُصدر على عنوان محجوز، والرفض يقع
    #     عندها **بعد** النشر — فيقع هنا قبله.
    case "$site_ip" in
        10.* | 127.* | 169.254.* | 192.168.* | 0.* | 100.6[4-9].* | 100.[7-9][0-9].* | 100.1[0-1][0-9].* | 100.12[0-7].*)
            fail "العنوان «$site_ip» غير عامّ، ولا تُصدر سلطة شهادات عليه شهادةً موثوقة." ;;
        172.1[6-9].* | 172.2[0-9].* | 172.3[0-1].*)
            fail "العنوان «$site_ip» غير عامّ، ولا تُصدر سلطة شهادات عليه شهادةً موثوقة." ;;
        fc* | fd* | fe8* | fe9* | fea* | feb* | ::1 | FC* | FD* | FE8* | FE9* | FEA* | FEB*)
            fail "العنوان «$site_ip» غير عامّ، ولا تُصدر سلطة شهادات عليه شهادةً موثوقة." ;;
    esac

    # (د) وبريدٌ حقيقي: حساب ACME لا يُنشأ بدونه. **ولا يُنتظَر منه إشعار
    #     انتهاء**: Let's Encrypt أوقفت خدمة إشعارات الانتهاء كلّها في
    #     2025-06-04، فمراقبة التجديد عملُ المالك وحده (‏README §3).
    if [ -z "$email" ]; then
        fail "‏BABEL_TLS_MODE=ip يتطلّب BABEL_TLS_EMAIL — حساب ACME لا يُنشأ بلا بريد."
    fi

    # والعنوان الذي تُقدَّم به الشهادة **يُشتقّ من الموقع ولا يُكتب ثانيةً**:
    # قيمتان يكتبهما إنسان تنحرف إحداهما، وانحرافُها هنا يعني حافةً تقلع
    # وشهادةً صحيحة ومصافحةً تسقط أمام الضيف — بلا رسالة خطأ واحدة.
    tls_ip="$site_ip"
fi

printf '%s\n' "$tls_ip"
