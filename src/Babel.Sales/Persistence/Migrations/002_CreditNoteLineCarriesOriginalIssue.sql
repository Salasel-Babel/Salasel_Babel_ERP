-- يُطلقه شيء.
--
-- **عمود واحد، nullable، بلا قيمة افتراضية، ولا صفّ واحد يُملأ بأثر رجعي.**
--   · nullable لأن null معنىً لا نقص: «تخفيض قيمة لا ردّ بضاعة».
--   · وبلا ملء رجعي لأن نسبة سطر إشعار قائم إلى سطر فاتورة بالتخمين تُنتج مرتجعاً
--     مُقيَّماً بتكلفة صرفٍ لم يقع — وهو بالضبط صنف العطل الذي وُضع له سجل المصائد.
--     (وقارن docs/evidence/traps.md#fakh-71: ملء عمود بأثر رجعي داخل بايتات
--     مُجزَّأة جعل دفتراً سليماً يُبلّغ عن عبث. هذا العمود خارج أي بايتات مُجزَّأة —
--     جدول وحدة لا جدول دفتر — ومع ذلك لا يُملأ، وللسبب المحاسبي لا التقني.)
