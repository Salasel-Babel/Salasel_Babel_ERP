using Babel.Contracts.Posting;

namespace Babel.Core.CapabilityProfile;

/// <summary>
/// فهرس رموز الأحداث في مصفوفة الترحيل — <b>الوجود فقط، لا القالب</b>.
/// <para>
/// النواة لا ترحّل ولا تعرف سطراً ولا دوراً ولا حساباً؛ وكل ما تحتاجه للحكم على ملفّ
/// قدرات مستأجر هو سؤال واحد: <b>هل هذا الحدث موجود في المصفوفة أصلاً؟</b> ولذلك هذا
/// العقد يجيب عن الوجود ولا يكشف شيئاً عن القالب.
/// </para>
/// <para>
/// ولماذا في النواة لا في الدفتر: اتجاه الاعتماد إلى الأسفل (القاعدة 3)، والنواة تحت
/// الدفتر فلا تراه. والملفّ يُحكَم عليه <b>عند الحفظ</b> — أي قبل أن يوجد قيد واحد —
/// فلا يجوز أن يتوقّف الحكم على تركيب الدفتر.
/// </para>
/// </summary>
public interface IPostingEventDirectory
{
    /// <summary>عدد رموز الأحداث المقروءة. حارس اللافراغ يعتمد عليه.</summary>
    int Count { get; }

    /// <summary>كل رموز الأحداث، مرتَّبة ترتيباً حرفياً ثابتاً.</summary>
    IReadOnlyList<PostingEventCode> Codes { get; }

    /// <summary>هل الحدث معرَّف في المصفوفة؟ الرمز غير المُسنَد ليس حدثاً ويُجاب عنه بلا.</summary>
    /// <param name="code">رمز الحدث.</param>
    bool Contains(PostingEventCode code);
}
