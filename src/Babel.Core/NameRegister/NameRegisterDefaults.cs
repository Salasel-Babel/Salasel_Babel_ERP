namespace Babel.Core.NameRegister;

/// <summary>
/// <b>العتبةُ والسقف — رقمان مقيسان، وفي موضعٍ واحد تراه الوحدات المالكة ووحدةُ الذكاء معاً.</b>
/// <para>
/// كانا في <c>LookupOptions</c> داخل وحدة الذكاء وحدها. ولمّا صارت كلُّ وحدةٍ مالكة تُسجّل
/// محوّلها بنفسها احتاجتهما، <b>ولا تستطيع أن ترى وحدة الذكاء</b> (القاعدة 3) — فكان
/// البديل أن يُكتب <c>0.45</c> سبعَ مرّات في سبعة ملفّات، ورقمٌ مكرَّر سبعاً ينحرف عند
/// السادسة ولا يُلاحَظ.
/// </para>
/// </summary>
public static class NameRegisterDefaults
{
    /// <summary>
    /// عتبة التشابه الثلاثي بعد الطيّ — <b>0.45 مقيسة لا مذوّقة</b>.
    /// <para>
    /// على هذا الجهاز (‏PostgreSQL 16 · pg_trgm) وبعد الطيّ: كلُّ زوجٍ يجب أن يتطابق يبلغ
    /// 1.000؛ و«محمد القحطاني»~«محمد الغامدي» يبلغ 0.350. والعتبة بينهما.
    /// </para>
    /// </summary>
    public const decimal SimilarityThreshold = 0.45m;

    /// <summary>سقف صفوف ورقة السؤال. ورقةٌ بلا سقف ليست سؤالاً بل جرداً.</summary>
    public const int QuestionSheetCap = 12;
}
