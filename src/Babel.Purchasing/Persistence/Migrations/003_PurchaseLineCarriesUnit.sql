-- هجرة المشتريات 003 — سطر المشتريات يحمل وحدة قياس كمّيته
-- ═══════════════════════════════════════════════════════════════════════════
--
-- كانت كمّية السطر عدداً مجرّداً: «عشرة». وهي تعبر إلى دفتر المخزون المساعد عند
-- ترحيل الاستلام، فتُضرب هناك في تكلفة الوحدة. و«عشرة» بلا وحدة **ليست معلومة**:
-- عشر حبّات أم عشر كراتين؟ والفرق بينهما في القيمة اثنا عشر ضعفاً على صنفٍ الكرتون
-- فيه اثنتا عشرة حبّة — **ولا يُظهره توازنٌ ولا سلسلة**، لأن القيد الناتج متوازن
-- تماماً. وهو صنف العطل الذي يفشل بصمت.
--
-- **والقيمة الافتراضية `EACH` لا فراغ:** الصفوف القائمة كُتبت كلّها بالعدّ — لا
-- مسار واحد في المنتج كان يقبل وحدةً أخرى قبل هذه الهجرة — فوسمُها بالعدّ **إفادةٌ
-- عن واقعة وقعت**، لا تخميناً. ولو تُركت فارغة لصار الرصيد المبنيّ عليها يُقرأ
-- «بوحدة مجهولة»، وهي حالةٌ لا يُمكن إصلاحها لاحقاً لأن أحداً لن يعرف ما كانت.
--
-- **وما لا تفعله هذه الهجرة:** لا تمسّ كمّيةً واحدة، ولا تُعيد حساب قيمة، ولا
-- تُحرّك رصيداً. إضافة عمودٍ وصفٍ لواقعةٍ مضت، لا إعادةُ كتابتها (‏ADR-0002).
--
-- والهجرة **معاملاتية** ومكتوبة لتُعاد بلا أثر.

do $migration$
begin
    -- قاعدة لم يُنشأ فيها المخطّط بعد ليست حالة خطأ: EnsureCreated ينشئ الشكل
    -- الجديد كاملاً، ولا شيء هنا ليُرقّى.
    if to_regclass('purchasing.purchase_line') is null then
        return;
    end if;

    alter table purchasing.purchase_line
        add column if not exists "Unit" character varying(32) not null default '';

    -- عمودٌ أُضيف في تشغيل سابق ثم عُدِّل بيدٍ خارجية: يُعاد إلى اصطلاح واحد.
    update purchasing.purchase_line set "Unit" = '' where "Unit" is null;

    -- الصفوف التي سبقت العمود تُوسَم بالعدّ — وهو ما كانت عليه فعلاً.
    update purchasing.purchase_line set "Unit" = 'EACH' where "Unit" = '';

    alter table purchasing.purchase_line alter column "Unit" set default '';
    alter table purchasing.purchase_line alter column "Unit" set not null;
end
$migration$;
