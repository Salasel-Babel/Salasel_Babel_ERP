namespace Babel.Contracts.Voice;

/// <summary>
/// من أين تأتي قيمةُ شريحةٍ في خطوةٍ من خطّة. <b>مصدران لا ثلاثة، ولا مصدرَ اسمه
/// «الافتراض».</b>
/// <para>
/// <b>ولماذا لا يوجد «من خطوةٍ سابقة»:</b> لأنه لا يستطيع أن يكون صادقاً هنا. <b>لا
/// خطوةَ في هذه المعمارية تحسب شيئاً</b> — كلُّ خطوةٍ تنتهي عند شاشة، والشاشةُ هي التي
/// تحلّ الاسم إلى معرّفٍ أمام عين الإنسان ثم تنادي العملية (‏<c>handoff.ts</c>). فليس
/// في يد الخطوة الأولى قيمةٌ تُسلّمها للثانية أصلاً. والمعرّف — وهو الشيء الوحيد الذي
/// كانت ستُسلّمه — <b>ممنوعٌ أن يحمله الصوت</b>، لأن حمله معناه مستندٌ صحيح الشكل على
/// عميلٍ آخر.
/// </para>
/// <para>
/// <b>وما يربط خطوتين إذاً هو الجملة نفسها.</b> «سند قبض من شركة المسار الأمثل» تُقرأ
/// اسماً في خطوة الإنشاء واسماً في خطوة السند — <b>النصّ نفسه من الفم نفسه</b>. وهذا
/// أقوى من تمريرٍ داخلي: لا يمرّ بين الخطوتين ما لم ينطقه إنسان.
/// </para>
/// </summary>
public enum VoiceSlotSource
{
    /// <summary>من الجملة الأولى كما نطقها الإنسان — تُقرأ في كل خطوةٍ من النصّ نفسه.</summary>
    FromUtterance = 1,

    /// <summary>
    /// تُطلَب من الإنسان بالاسم حين تنقص. <b>وتُطلَب صوتاً فقط لأن النيّة تُعلنها
    /// شريحةً</b>؛ وما لا تُعلنه النيّة حقلُ شاشةٍ لا يُسأل عنه بالصوت — وهو ما تسمّيه
    /// <see cref="VoicePlanStep.ScreenAsksForAr"/> جهراً في التوجيه.
    /// </summary>
    AskedOfHuman = 2,
}
